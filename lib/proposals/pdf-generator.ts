// Queenstown Lead Intelligence - Professional Commercial Proposal PDF Generator

import { jsPDF } from 'jspdf';
import { ProposalData } from '../ai/gemini';

export function createProposalPdfDocument(proposal: ProposalData): jsPDF {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 20;

  // Header / Brand Title
  doc.setFillColor(15, 23, 42); // Brand Dark #0F172A
  doc.rect(0, 0, pageWidth, 28, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('QUEENSTOWN LABS', 20, 14);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('BESPOKE SOFTWARE ENGINEERING & DIGITAL TRANSFORMATION', 20, 21);

  y = 38;

  // Proposal Title & Client Box
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(15);
  doc.setFont('helvetica', 'bold');
  doc.text(proposal.project_title, 20, y);

  y += 7;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text(`Prepared for: ${proposal.client_name} | Date: ${new Date().toLocaleDateString()}`, 20, y);

  y += 10;
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(20, y, pageWidth - 20, y);

  y += 8;

  // Executive Summary
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('1. Executive Summary', 20, y);

  y += 6;
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(51, 65, 85);
  const execLines = doc.splitTextToSize(proposal.executive_summary, pageWidth - 40);
  doc.text(execLines, 20, y);
  y += execLines.length * 4.5 + 4;

  // Problem & Solution
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text('2. Operational Challenge & Proposed Architecture', 20, y);

  y += 6;
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text('Challenge:', 20, y);
  doc.setFont('helvetica', 'normal');
  const probLines = doc.splitTextToSize(proposal.problem_statement, pageWidth - 60);
  doc.text(probLines, 45, y);
  y += probLines.length * 4.5 + 4;

  doc.setFont('helvetica', 'bold');
  doc.text('Solution:', 20, y);
  doc.setFont('helvetica', 'normal');
  const solLines = doc.splitTextToSize(proposal.proposed_solution, pageWidth - 60);
  doc.text(solLines, 45, y);
  y += solLines.length * 4.5 + 6;

  // Scope of Work Modules
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text('3. Scope of Work & Deliverables', 20, y);
  y += 6;

  proposal.scope_of_work.forEach((item, idx) => {
    if (y > 260) {
      doc.addPage();
      y = 20;
    }
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(16, 185, 129); // Brand Accent #10B981
    doc.text(`Module ${idx + 1}: ${item.module_name}`, 20, y);
    y += 5;

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(71, 85, 105);
    const modDesc = doc.splitTextToSize(item.description, pageWidth - 40);
    doc.text(modDesc, 20, y);
    y += modDesc.length * 4.5 + 4;
  });

  // Milestones & Commercials
  if (y > 220) {
    doc.addPage();
    y = 20;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text('4. Timeline & Milestone Estimates', 20, y);
  y += 6;

  // Table header
  doc.setFillColor(241, 245, 249);
  doc.rect(20, y, pageWidth - 40, 7, 'F');
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text('Phase / Milestone', 24, y + 5);
  doc.text('Duration', 110, y + 5);
  doc.text('Investment (USD)', 150, y + 5);
  y += 8;

  proposal.milestones.forEach((m) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(51, 65, 85);
    doc.text(m.phase, 24, y + 4);
    doc.text(`${m.duration_weeks} weeks`, 110, y + 4);
    doc.text(`$${m.estimated_cost_usd.toLocaleString()}`, 150, y + 4);
    y += 6;
  });

  y += 3;
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text(
    `Total Estimated Investment: $${proposal.estimated_total_cost_usd.toLocaleString()} USD | Total Duration: ${proposal.estimated_timeline_weeks} Weeks`,
    20,
    y
  );

  y += 10;

  // Footer / Terms
  doc.setFontSize(8);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(148, 163, 184);
  doc.text(
    'This commercial proposal is generated by Queenstown Labs Lead Intelligence Engine and is subject to formal statement of work sign-off.',
    20,
    y
  );

  return doc;
}
